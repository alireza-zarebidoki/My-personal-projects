#include <stdlib.h>  // برای atoi، malloc، exit و توابع عمومی
#include <string.h>  // برای strcpy، strcat، strcmp و عملیات رشته‌ای
#include <time.h>    // برای srand، time و تولید اعداد تصادفی در بازی‌ها

