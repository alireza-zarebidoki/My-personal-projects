/*
 * print_header: تولید هدر HTML یکپارچه برای تمام بازی‌های CGI
 *
 * این تابع اولین چیزی است که در هر بازی CGI صدا می‌زنم.
 * هدفم ساخت یک ظاهر ثابت و حرفه‌ای برای تمام بازی‌ها بود.
 *
 * چرا این رویکرد را انتخاب کردم:
 * - نمی‌خواستم برای هر بازی فایل CSS جداگانه بسازم
 * - تغییرات ظاهری از یک جا اعمال می‌شوند
 * - بازی‌ها در iframe نمایش داده می‌شوند و نیاز به استایل مستقل دارند
 * - استایل inline سریع‌تر load می‌شود
 *
 * ساختار HTML که تولید می‌کنم:
 * 1. Content-Type header (برای مرورگر)
 * 2. DOCTYPE و تگ html با lang="fa" و dir="rtl"
 * 3. تگ head شامل:
 *    - charset UTF-8 (برای نمایش صحیح فارسی)
 *    - title صفحه
 *    - لینک به فونت Vazirmatn (فارسی زیبا)
 *    - لینک به Font Awesome (آیکون‌ها)
 *    - استایل inline (border، background، button و...)
 * 4. تگ body و یک div با class="game-container"
 *
 * @param title: عنوان بازی که در تب مرورگر نمایش داده می‌شود
 *        - به صورت "[title] | Arcade System" نمایش می‌یابد
 *        - می‌تواند فارسی یا انگلیسی باشد
 *        - اگر NULL باشد، فقط "Arcade System" نمایش می‌یابد (توصیه نمی‌شود)
 *
 * استایل‌هایی که اعمال می‌کنم:
 * - body: پس‌زمینه transparent (چون در iframe است)
 * - font-family: Vazirmatn (فونت فارسی حرفه‌ای)
 * - overflow-y: auto (اسکرول عمودی در صورت نیاز)
 * - .game-container:
 *   - padding بالا زیاد (120px) تا جای دکمه‌های کابینت خالی بماند
 *   - border سبز نئونی (#10b981)
 *   - background سیاه با شفافیت
 *   - border-radius برای گوشه‌های گرد
 * - input: استایل مشکی با border سبز
 * - button: دکمه‌های سبز با فونت bold
 *
 * نکات مهم:
 * - حتماً باید اولین چیزی باشد که در CGI چاپ می‌شود
 * - هیچ چیز نباید قبل از Content-Type چاپ شود (حتی فاصله!)
 * - باید با print_footer بسته شود
 *
 * چرا استایل را inline نوشتم:
 * - فایل CSS جداگانه نیاز به مسیر و درخواست HTTP اضافی دارد
 * - در CGI ساده‌تر است که همه چیز در یک خروجی باشد
 * - برای بازی‌های کوچک من کافی است
 * - تغییرات سریع‌تر اعمال می‌شوند
 *
 * اگر این تابع را حذف کنم:
 * - هر بازی باید HTML کامل خودش را داشته باشد
 * - ظاهر بازی‌ها ناهماهنگ می‌شود
 * - تغییر استایل نیازمند ویرایش همه فایل‌های CGI است
 */
void print_header(const char *title) {
    // مرحله 1: ارسال Content-Type به مرورگر
    // این header حیاتی است و باید اولین خروجی باشد
    // charset=utf-8 را اضافه می‌کنم تا فارسی درست نمایش یابد
    // دو newline در انتها الزامی است (یکی پایان header، یکی جداکننده)
    printf("Content-Type: text/html; charset=utf-8\n\n");

    // مرحله 2: شروع ساختار HTML5
    // DOCTYPE مدرن بدون پارامتر اضافی
    printf("<!DOCTYPE html>\n");

    // تگ html با ویژگی‌های مناسب برای فارسی:
    // - lang='fa': زبان فارسی (به SEO و screen reader کمک می‌کند)
    // - dir='rtl': جهت راست‌به‌چپ (برای صحیح نمایش فارسی)
    printf("<html lang='fa' dir='rtl'>\n");

    // مرحله 3: باز کردن head و تنظیمات پایه
    printf("<head>\n");

    // charset را مجدداً در meta تگ مشخص می‌کنم
    // این برای مرورگرهای قدیمی‌تر مفید است
    printf("    <meta charset='UTF-8'>\n");

    // عنوان صفحه را با فرمت "[title] | Arcade System" چاپ می‌کنم
    // %s به جای title قرار می‌گیرد
    printf("    <title>%s | Arcade System</title>\n", title);

    // مرحله 4: بارگذاری فونت‌ها و آیکون‌ها از CDN
    // اول Font Awesome برای آیکون‌های زیبا (قلب، ستاره، چک و...)
    printf("    <link rel='stylesheet' href='https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.0.0/css/all.min.css'>\n");

    // بعد فونت Vazirmatn که یک فونت فارسی زیبا و حرفه‌ای است
    // از CDN jsDelivr + GitHub استفاده می‌کنم که سریع و قابل اعتماد است
    printf("    <link href='https://cdn.jsdelivr.net/gh/rastikerdar/vazirmatn@v33.003/Vazirmatn-font-face.css' rel='stylesheet'>\n");

    // مرحله 5: استایل‌های inline
    // عمداً stylesheet اصلی کابینت را اینجا تزریق نمی‌کنم
    // چون می‌خواهم ظاهر iframe مستقل از صفحه اصلی باشد
    printf("    <style>\n");

    // استایل body: پس‌زمینه transparent تا با کابینت ترکیب شود
    printf("        body { background: transparent; font-family: 'Vazirmatn', sans-serif; overflow-y: auto; text-align: center; }\n");

    // استایل کانتینر اصلی بازی:
    // - padding-top: 120px -> جای کافی برای دکمه‌های بالای کابینت
    // - border: 2px solid #10b981 -> حاشیه سبز نئونی
    // - border-radius: 10px -> گوشه‌های گرد
    // - background: rgba(0,0,0,0.9) -> سیاه با کمی شفافیت
    // - max-width: 100% -> responsive بودن
    // - margin: 40px auto -> فاصله از بالا و وسط‌چین
    // - overflow: visible -> محتوای بیرونی بریده نشود
    // - color: #e5e7eb -> متن خاکستری روشن
    printf("        .game-container { padding: 120px 10px 20px 10px; border: 2px solid #10b981; border-radius: 10px; background: rgba(0,0,0,0.9); max-width: 100%%; margin: 40px auto; overflow: visible; color: #e5e7eb; }\n");

    // تمام عناصر متنی داخل کانتینر باید رنگ روشن داشته باشند
    // این را برای خوانایی روی پس‌زمینه تیره اعمال می‌کنم
    printf("        .game-container h1, .game-container h2, .game-container h3, .game-container p, .game-container div, .game-container form, .game-container label { color: #e5e7eb; }\n");

    // استایل input برای فیلدهای ورودی:
    // - background: #000 -> پس‌زمینه مشکی
    // - color: #fff -> متن سفید
    // - border: 1px solid #10b981 -> حاشیه سبز
    // - padding: 8px 10px -> فاصله داخلی مناسب
    // - border-radius: 6px -> گوشه‌های گرد
    printf("        .game-container input[type=number], .game-container input[type=text] { background:#000; color:#fff; border:1px solid #10b981; padding:8px 10px; border-radius:6px; }\n");

    // استایل button برای دکمه‌ها:
    // - background: #10b981 -> سبز نئونی (رنگ اصلی تم)
    // - color: #000 -> متن مشکی (کنتراست بالا)
    // - border: none -> بدون حاشیه
    // - padding: 10px 20px -> فاصله داخلی مناسب
    // - cursor: pointer -> نشانگر دست هنگام hover
    // - font-weight: 900 -> فونت خیلی bold
    // - border-radius: 6px -> گوشه‌های گرد
    printf("        .game-container button { background: #10b981; color: #000; border: none; padding: 10px 20px; cursor: pointer; font-weight: 900; border-radius: 6px; }\n");

    // پایان بلوک style
    printf("    </style>\n");

    // مرحله 6: بستن head و باز کردن body
    printf("</head>\n");
    printf("<body>\n");

    // مرحله 7: باز کردن کانتینر اصلی بازی
    // این div در print_footer بسته می‌شود
    // تمام محتوای بازی داخل این div قرار می‌گیرد
    printf("<div class='game-container'>\n");

    // حالا بازی می‌تواند محتوای خود را چاپ کند
    // باید در پایان print_footer صدا زده شود
}

