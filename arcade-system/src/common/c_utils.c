/*
 * print_footer: بستن ساختار HTML و اتمام صفحه
 *
 * این تابع آخرین چیزی است که در هر CGI صدا می‌زنم.
 * وظیفه‌اش بستن تمام تگ‌های باز شده در print_header است.
 *
 * چرا این تابع مهم است:
 * - اگر تگ‌ها باز بمانند، HTML ناقص و معیوب می‌شود
 * - بعضی مرورگرها محتوای ناقص را اصلاً نمایش نمی‌دهند
 * - استایل‌ها ممکن است به درستی اعمال نشوند
 * - ابزارهای توسعه مرورگر خطا نشان می‌دهند
 *
 * ترتیب بستن تگ‌ها (معکوس باز شدن):
 * 1. </div> -> بستن game-container که در print_header باز شد
 * 2. </body> -> بستن بدنه صفحه
 * 3. </html> -> بستن ریشه HTML
 *
 * این تابع هیچ پارامتری ندارد چون همیشه یک کار ثابت انجام می‌دهد.
 *
 * نکات مهم:
 * - باید آخرین چیزی باشد که در CGI اجرا می‌شود
 * - اگر چند مسیر خروج در کد داری، در همه جاها صدا بزن
 * - بعد از این تابع نباید چیزی چاپ کنی
 *
 * مثال استفاده صحیح:
 *   print_header("بازی من");
 *   // ... محتوای بازی ...
 *   print_footer();
 *   return 0;
 *
 * اگر این تابع را فراموش کنم:
 * - HTML ناقص می‌شود
 * - مرورگر سعی می‌کند خودش تگ‌ها را ببندد (نتیجه غیرقابل پیش‌بینی)
 * - validator HTML خطا می‌دهد
 * - در بعضی مرورگرها محتوا به درستی نمایش داده نمی‌شود
 *
 * یادآوری برای خودم:
 * - همیشه با print_header جفت است
 * - در همه مسیرهای خروج از main صدا بزن
 * - ساده‌ترین ولی حیاتی‌ترین تابع
 */
void print_footer() {
    // بستن div کانتینر بازی که در print_header باز کردیم
    printf("</div>\n");

    // بستن تگ body
    printf("</body>\n");

    // بستن تگ html و پایان سند
    printf("</html>\n");

    // حالا HTML کامل است و مرورگر می‌تواند صفحه را رندر کند
    // بعد از اینجا نباید چیزی چاپ شود
}

