/*
 * get_param: خواندن یک پارامتر از ورودی CGI
 *
 * این تابع قلب سیستم ورودی من است. CGI می‌تواند داده را از دو راه دریافت کند:
 * 1. GET: داده در QUERY_STRING (بخشی از URL بعد از ?) است
 * 2. POST: داده در stdin (ورودی استاندارد) است
 *
 * مراحل کار این تابع:
 * 1. ابتدا value را خالی می‌کنم تا اگر چیزی پیدا نشد، مقدار قبلی نماند
 * 2. یک بافر بزرگ (دو برابر MAX_BUFFER) می‌سازم برای خواندن کل ورودی
 * 3. REQUEST_METHOD را چک می‌کنم (GET یا POST)
 * 4. اگر POST است، CONTENT_LENGTH را می‌خوانم و از stdin می‌خوانم
 * 5. اگر GET است یا POST خالی بود، QUERY_STRING را می‌خوانم
 * 6. رشته را با '&' می‌شکنم و هر قطعه را بررسی می‌کنم
 * 7. اگر key مطابقت داشت، value را extract می‌کنم
 * 8. URL decode می‌کنم (%20 -> space و...)
 * 9. نتیجه را در بافر value کپی می‌کنم
 *
 * @param key: نام پارامتری که دنبالش می‌گردم (مثل "move", "level", "secret")
 *        - باید دقیقاً مطابق باشد (case-sensitive)
 *        - اگر در ورودی نباشد، value خالی می‌ماند
 *
 * @param value: بافر مقصد برای نوشتن مقدار پیدا شده
 *        - باید حداقل MAX_BUFFER بایت داشته باشد
 *        - اگر پارامتر پیدا نشود، رشته خالی می‌شود
 *        - مقدار پس از URL decoding است
 *
 * مثال‌های استفاده:
 *   // URL: game.cgi?level=3&move=5
 *   char buf[MAX_BUFFER];
 *   get_param("level", buf);  // buf = "3"
 *   int level = atoi(buf);     // level = 3
 *
 *   get_param("move", buf);    // buf = "5"
 *   int move = atoi(buf);      // move = 5
 *
 *   get_param("notexist", buf); // buf = "" (empty)
 *
 * نکات مهم:
 * - این تابع فقط اولین مقداری که key را دارد برمی‌گرداند
 * - اگر key چند بار تکرار شود، فقط اولی گرفته می‌شود
 * - فضاهای خالی و کاراکترهای خاص به درستی decode می‌شوند
 *
 * محدودیت‌ها:
 * - اگر طول کل ورودی از (MAX_BUFFER * 2) بیشتر باشد، بریده می‌شود
 * - برای بازی‌های من این مشکلی نیست
 * - اگر نیاز به ورودی بزرگ‌تر باشد، باید بافر را بزرگ‌تر کنم
 *
 * خطرات امنیتی که رفع کردم:
 * - سرریز بافر: با محدود کردن fread جلوگیری شد
 * - کاراکترهای خطرناک: URL decode آن‌ها را تمیز می‌کند
 * - حافظه تصادفی: بافر را قبل از استفاده خالی می‌کنم
 */
void get_param(const char *key, char *value) {
    // مرحله 1: مقداردهی اولیه - value را خالی می‌کنم
    // اگر این کار را نکنم، ممکن است مقدار قدیمی در بافر بماند
    value[0] = '\0';

    // مرحله 2: آماده‌سازی بافر اصلی
    // این بافر محلی است و پس از پایان تابع آزاد می‌شود
    // دو برابر MAX_BUFFER تا هم POST و هم GET را بتوانم بخوانم
    char query_buf[MAX_BUFFER * 2];
    query_buf[0] = '\0';  // ابتدا خالی می‌کنم
    size_t qlen = 0;       // طول واقعی دادهٔ خوانده شده

    // مرحله 3: تشخیص متد درخواست (GET یا POST)
    // getenv یک تابع استاندارد C است که متغیرهای محیطی CGI را می‌خواند
    char *method = getenv("REQUEST_METHOD");

    // مرحله 4: اگر POST است، داده را از stdin بخوان
    if (method && strcmp(method, "POST") == 0) {
        // طول محتوا را از CONTENT_LENGTH می‌خوانم تا بدانم چقدر بخوانم
        char *content_length_str = getenv("CONTENT_LENGTH");

        if (content_length_str) {
            // رشته را به عدد تبدیل می‌کنم
            int len = atoi(content_length_str);

            if (len > 0) {
                // محافظت از سرریز بافر: اگر بیشتر از حد بود، محدود می‌کنم
                // -1 برای null terminator است
                if (len > (int)sizeof(query_buf) - 1) {
                    len = (int)sizeof(query_buf) - 1;
                }

                // از stdin (ورودی استاندارد) می‌خوانم
                // fread بایت‌های خام را می‌خواند
                size_t r = fread(query_buf, 1, (size_t)len, stdin);

                // null terminator اضافه می‌کنم تا رشته معتبر باشد
                query_buf[r] = '\0';
                qlen = r;  // طول واقعی خوانده شده را ذخیره می‌کنم
            }
        }
    }

    // مرحله 5: اگر POST خالی بود یا GET بود، QUERY_STRING را بخوان
    // این fallback برای حالت GET است یا وقتی POST داده ندارد
    if (qlen == 0) {
        char *env_query = getenv("QUERY_STRING");

        if (env_query) {
            // امن‌تر از strcpy چون طول را محدود می‌کنم
            strncpy(query_buf, env_query, sizeof(query_buf) - 1);
            query_buf[sizeof(query_buf) - 1] = '\0';  // اطمینان از null termination
            qlen = strlen(query_buf);
        }
    }

    // مرحله 6: اگر هیچ داده‌ای نیامده، برگرد
    // value از قبل خالی است پس نیازی به کار دیگری نیست
    if (qlen == 0) return;

    // مرحله 7: پارس کردن query string
    // فرمت: key1=value1&key2=value2&key3=value3
    // باید هر جفت key=value را جدا کنم و با key مقایسه کنم

    char *cursor = query_buf;  // پوینتری که از اول شروع می‌کند

    while (cursor && *cursor) {
        // پیدا کردن محل '&' بعدی که جداکننده پارامترهاست
        char *amp = strchr(cursor, '&');

        // محاسبه طول این token (تا '&' یا تا آخر رشته)
        size_t token_len = amp ? (size_t)(amp - cursor) : strlen(cursor);

        // محافظت از سرریز: اگر token خیلی بلند است، کوتاهش می‌کنم
        if (token_len >= sizeof(query_buf)) {
            token_len = sizeof(query_buf) - 1;
        }

        // کپی کردن این بخش به یک بافر موقت برای پردازش
        char token[MAX_BUFFER * 2];
        memcpy(token, cursor, token_len);
        token[token_len] = '\0';

        // پیدا کردن '=' که key و value را جدا می‌کند
        char *eq = strchr(token, '=');

        if (eq) {
            // '=' را به null تبدیل می‌کنم تا دو رشته جدا شوند
            *eq = '\0';

            char *k = token;      // key قبل از '=' است
            char *v = eq + 1;     // value بعد از '=' است

            // مقایسه key: آیا همان چیزی است که دنبالش می‌گردم؟
            if (strcmp(k, key) == 0) {
                // پیدا شد! حالا باید URL decode کنم
                // چون value ممکن است %20 (فاصله) یا کاراکترهای دیگر داشته باشد
                url_decode_internal(v);

                // کپی کردن نتیجه به بافر خروجی
                // از strncpy استفاده می‌کنم تا از سرریز جلوگیری کنم
                strncpy(value, v, MAX_BUFFER - 1);
                value[MAX_BUFFER - 1] = '\0';  // اطمینان از null termination

                // پیدا شد، دیگر نیازی به ادامه جستجو نیست
                return;
            }
        }

        // حرکت به پارامتر بعدی
        if (!amp) break;  // اگر '&' نبود یعنی به آخر رسیدیم
        cursor = amp + 1;  // از کاراکتر بعد '&' ادامه بده
    }

    // اگر به اینجا رسیدیم، یعنی key پیدا نشد
    // value از قبل خالی است پس نیازی به کار دیگری نیست
}

