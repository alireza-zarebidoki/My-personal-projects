/*
 * url_decode_internal: رمزگشایی URL encoding به متن خام
 *
 * این تابع را خودم نوشتم چون نمی‌خواستم به کتابخانه خارجی وابسته باشم.
 * CGI پارامترها را به صورت URL-encoded می‌فرستد و من باید آن‌ها را decode کنم.
 *
 * نحوه کار:
 * 1. رشته را کاراکتر به کاراکتر می‌پیمایم
 * 2. اگر '%' دیدم، دو کاراکتر بعدی را به عنوان hex می‌خوانم
 * 3. عدد hex را به کاراکتر واقعی تبدیل می‌کنم
 * 4. اگر '+' دیدم، به فاصله تبدیل می‌کنم
 * 5. بقیه کاراکترها را همان‌طور کپی می‌کنم
 *
 * @param str: رشته‌ای که می‌خواهم درجا (in-place) decode کنم
 *        - اگر NULL باشد هیچ کاری نمی‌کنم
 *        - نتیجه در همان بافر نوشته می‌شود (طول کوچک‌تر یا مساوی می‌شود)
 *
 * مثال:
 *   "hello+world%20test" -> "hello world test"
 *   "%D8%B3%D9%84%D8%A7%D9%85" -> "سلام" (UTF-8 encoded)
 *
 * چرا in-place است:
 * - حافظه اضافی لازم نیست
 * - decode همیشه رشته را کوتاه‌تر یا هم‌اندازه می‌کند
 * - سرعت بیشتر و پیچیدگی کمتر
 *
 * خطرات:
 * - اگر فرمت hex اشتباه باشد (مثلاً %ZZ)، ممکن است کاراکتر نامعتبر تولید شود
 * - فعلاً validation ندارم ولی برای بازی‌های من کافی است
 *
 * نکته امنیتی:
 * - این تابع فرض می‌کند ورودی از منبع قابل اعتماد (CGI server) است
 * - اگر بخواهم از ورودی کاربر مستقیم استفاده کنم، باید validation اضافه کنم
 */
void url_decode_internal(char *str) {
    // اگر رشته NULL بود، هیچ کاری نمی‌کنم تا crash نکنم
    if (!str) return;

    // دو پوینتر: یکی برای خواندن (pstr)، یکی برای نوشتن (pdst)
    // چون decode همیشه طول را کوتاه‌تر یا برابر می‌کند، جای نوشتن همیشه در دسترس است
    char *pstr = str;   // پوینتر خواندن: از اول رشته شروع می‌کنم
    char *pdst = str;   // پوینتر نوشتن: همان جا می‌نویسم

    // تا آخر رشته ادامه می‌دهم (null terminator)
    while (*pstr) {
        if (*pstr == '%' && pstr[1] && pstr[2]) {
            // اگر '%' دیدم و دو کاراکتر بعدی موجود است
            // این یک کد hex است مثل %20 برای فاصله

            // دو کاراکتر hex را در آرایه موقت می‌گذارم
            char hex[3] = { pstr[1], pstr[2], '\0' };

            // hex را به عدد (base 16) تبدیل می‌کنم و به کاراکتر cast می‌کنم
            *pdst = (char)strtol(hex, NULL, 16);

            // سه کاراکتر را از ورودی رد کردم (%XX)
            pstr += 3;
        } else if (*pstr == '+') {
            // '+' در URL encoding معادل فاصله است
            // این قرارداد قدیمی است ولی هنوز کار می‌کند
            *pdst = ' ';
            pstr++;
        } else {
            // کاراکتر معمولی است، همان‌طور کپی می‌کنم
            *pdst = *pstr;
            pstr++;
        }

        // پوینتر نوشتن را یک قدم جلو می‌برم
        pdst++;
    }

    // رشته را با null terminator می‌بندم
    *pdst = '\0';
}

