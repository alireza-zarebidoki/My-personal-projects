/*
 * ═══════════════════════════════════════════════════════════════════════════
 *                      بازی حدس عدد پیشرفته (Guess Number Game)
 *                              guess_number.c
 * ═══════════════════════════════════════════════════════════════════════════
 *
 * این بازی را من طراحی کردم تا یک نسخه پیشرفته از بازی کلاسیک حدس عدد باشد.
 *
 * ویژگی‌های بازی:
 * - سه سطح دشواری: آسان، متوسط، سخت
 * - سیستم راهنمایی هوشمند (گرم/سرد)
 * - محدودیت تعداد تلاش‌ها بر اساس سطح
 * - فیدبک بصری جذاب
 * - نگهداری state بین درخواست‌ها
 *
 * سطوح دشواری:
 * - آسان: 10 تلاش + تنگ شدن بازه + راهنمایی زوج/فرد
 * - متوسط: 7 تلاش + راهنمایی استاندارد
 * - سخت: 5 تلاش + فقط راهنمایی حرارتی (بدون جهت)
 *
 * معماری:
 * - CGI-based: هر action یک درخواست HTTP جدید
 * - Stateless: تمام state در URL parameters نگهداری می‌شود
 * - از c_utils.h برای HTML wrapper استفاده می‌کند
 *
 * Flow بازی:
 * 1. نمایش منوی انتخاب سطح (game_state = 0)
 * 2. مقداردهی اولیه بازی با level انتخابی (mode=start)
 * 3. حلقه بازی: حدس → بررسی → فیدبک (mode=play)
 * 4. پایان: برد (game_state = 2) یا باخت (game_state = 3)
 *
 * یادآوری برای خودم:
 * - secret باید همیشه در URL باقی بماند تا بین requests حفظ شود
 * - srand(time(NULL)) برای random واقعی ضروری است
 * - تمام متون باید فارسی باشند برای یکپارچگی UI
 */

#include "../common/c_utils.h"
#include <time.h>

// ═══════════════════════════════════════════════════════════════════════════
//                              ثابت‌های بازی
// ═══════════════════════════════════════════════════════════════════════════

/*
 * سطوح دشواری
 *
 * این ثابت‌ها را تعریف کردم تا کد خواناتر باشد و اگر بخواهم سطح جدید اضافه کنم،
 * فقط اینجا تغییر بدهم.
 *
 * مقادیر:
 * - LEVEL_EASY = 1: حالت آسان (10 تلاش، راهنمایی کامل)
 * - LEVEL_MEDIUM = 2: حالت متوسط (7 تلاش، راهنمایی معمولی)
 * - LEVEL_HARD = 3: حالت سخت (5 تلاش، راهنمایی محدود)
 *
 * چرا از #define:
 * - const int به حافظه نیاز دارد
 * - این مقادیر هرگز تغییر نمی‌کنند
 * - preprocessor این‌ها را جایگزین می‌کند (بهینه‌تر)
 */
#define LEVEL_EASY 1
#define LEVEL_MEDIUM 2
#define LEVEL_HARD 3

// ═══════════════════════════════════════════════════════════════════════════
//                              توابع کمکی
// ═══════════════════════════════════════════════════════════════════════════

/*
 * تابع get_random_int - تولید عدد تصادفی در بازه
 *
 * این تابع را نوشتم تا هر جا که نیاز به عدد تصادفی دارم، کد تکراری ننویسم.
 *
 * چرا این تابع:
 * - rand() % range یک الگوی رایج است که می‌توان تابع کرد
 * - خوانایی کد بالا می‌رود: get_random_int(1, 100) واضح‌تر از rand()%100+1 است
 * - اگر بخواهم الگوریتم random را تغییر بدهم، فقط اینجا تغییر می‌دهم
 *
 * نحوه کار:
 * - rand() یک عدد بین 0 تا RAND_MAX تولید می‌کند
 * - % (max - min + 1) آن را به بازه 0 تا (max-min) محدود می‌کند
 * - + min آن را به بازه min تا max منتقل می‌کند
 *
 * مثال:
 * - get_random_int(1, 100) → عددی بین 1 تا 100
 * - get_random_int(10, 20) → عددی بین 10 تا 20
 *
 * نکته: قبل از استفاده باید srand(time(NULL)) فراخوانی شده باشد!
 *
 * @param min: کمترین عدد ممکن (inclusive)
 * @param max: بیشترین عدد ممکن (inclusive)
 * @return: عدد تصادفی در بازه [min, max]
 */
int get_random_int(int min, int max) {
    return min + rand() % (max - min + 1);
}

// ═══════════════════════════════════════════════════════════════════════════
//                          تابع اصلی - نقطه ورود CGI
// ═══════════════════════════════════════════════════════════════════════════

/*
 * تابع main - نقطه ورود برنامه CGI
 *
 * این تابع قلب برنامه است. هر بار که کاربر صفحه را لود می‌کند یا فرمی را
 * submit می‌کند، این تابع از ابتدا اجرا می‌شود.
 *
 * معماری CGI (Stateless):
 * - هر request یک execution جدید است
 * - state بین requests در URL parameters نگهداری می‌شود
 * - هیچ چیزی در memory سرور باقی نمی‌ماند
 *
 * Flow اجرا:
 * 1. مقداردهی اولیه (srand، print_header)
 * 2. خواندن parameters از URL
 * 3. پردازش منطق بازی بر اساس mode
 * 4. تولید HTML خروجی
 * 5. پایان (print_footer)
 *
 * چرا این معماری:
 * - ساده است (بدون نیاز به database یا session management)
 * - امن است (state در کنترل کاربر است)
 * - scalable است (هر request مستقل است)
 *
 * یادآوری برای خودم:
 * - همیشه باید secret را در hidden field نگه دارم
 * - srand باید قبل از هر استفاده از rand() باشد
 * - تمام HTML باید valid باشد (برای compatibility)
 */
int main() {
    // ───────────────────────────────────────────────────────────────────────
    // بخش ۱: مقداردهی اولیه
    // ───────────────────────────────────────────────────────────────────────

    /*
     * seed کردن random number generator
     *
     * time(NULL) تعداد ثانیه‌ها از 1 ژانویه 1970 را برمی‌گرداند.
     * با استفاده از این به عنوان seed، هر بار که برنامه اجرا شود،
     * دنباله اعداد تصادفی متفاوت خواهد بود.
     *
     * چرا اینجا: هر request یک execution جدید است، پس باید هر بار seed کنیم.
     */
    srand(time(NULL));

    /*
     * چاپ header HTML
     *
     * این تابع از c_utils.h می‌آید و HTML پایه را چاپ می‌کند:
     * - DOCTYPE و meta tags
     * - عنوان صفحه
     * - CSS های مشترک
     * - شروع body
     */
    print_header("بازی حدس عدد پیشرفته");

    // ───────────────────────────────────────────────────────────────────────
    // بخش ۲: تعریف متغیرهای state
    // ───────────────────────────────────────────────────────────────────────

    /*
     * این متغیرها وضعیت فعلی بازی را نگه می‌دارند.
     *
     * چرا -1 برای مقادیر اولیه:
     * - برای تشخیص اینکه آیا parameter در URL بود یا نه
     * - 0 یک مقدار معتبر است (مثلاً attempts=0)
     * - -1 یعنی "هنوز مقداردهی نشده"
     */
    char buffer[MAX_BUFFER];  // بافر موقت برای خواندن parameters
    int secret = -1;          // عدد مخفی که باید حدس زده شود
    int attempts = -1;        // تعداد تلاش‌های باقی‌مانده
    int min_range = 1;        // کف بازه (برای حالت آسان)
    int max_range = 100;      // سقف بازه (برای حالت آسان)
    int level = 0;            // سطح دشواری (0=منو، 1=آسان، 2=متوسط، 3=سخت)
    int guess = -1;           // آخرین حدس کاربر
    int game_state = 0;       // 0=منو، 1=در حال بازی، 2=برد، 3=باخت

    // ───────────────────────────────────────────────────────────────────────
    // بخش ۳: خواندن parameters از URL
    // ───────────────────────────────────────────────────────────────────────

    /*
     * این بخش تمام parameters را از query string می‌خواند.
     *
     * get_param از c_utils.h می‌آید و:
     * - query string را parse می‌کند
     * - parameter مورد نظر را پیدا می‌کند
     * - URL decode می‌کند
     * - در buffer قرار می‌دهد
     *
     * الگوی استفاده:
     * 1. get_param("name", buffer) را صدا بزن
     * 2. اگر buffer[0] != '\0' باشد، parameter وجود داشته
     * 3. با atoi() به int تبدیل کن
     */

    // mode: مشخص می‌کند کاربر در کدام مرحله است (start, play)
    get_param("mode", buffer);
    char mode[50];
    strcpy(mode, buffer);

    // level: سطح دشواری انتخاب شده (1، 2، 3)
    get_param("level", buffer);
    if (buffer[0]) level = atoi(buffer);

    // secret: عدد مخفی (باید بین requests حفظ شود)
    get_param("secret", buffer);
    if (buffer[0]) secret = atoi(buffer);

    // attempts: تعداد تلاش‌های باقی‌مانده
    get_param("attempts", buffer);
    if (buffer[0]) attempts = atoi(buffer);

    // min: حد پایین بازه فعلی (برای حالت آسان)
    get_param("min", buffer);
    if (buffer[0]) min_range = atoi(buffer);

    // max: حد بالای بازه فعلی (برای حالت آسان)
    get_param("max", buffer);
    if (buffer[0]) max_range = atoi(buffer);

    // guess: آخرین حدس کاربر
    get_param("guess", buffer);
    if (buffer[0]) guess = atoi(buffer);

    // ───────────────────────────────────────────────────────────────────────
    // بخش ۴: منطق بازی (Game Logic)
    // ───────────────────────────────────────────────────────────────────────

    /*
     * حالت start: کاربر سطح دشواری را انتخاب کرده و بازی شروع می‌شود
     *
     * در این حالت:
     * - یک عدد تصادفی تولید می‌کنیم (secret)
     * - بازه را مقداردهی می‌کنیم (1-100)
     * - تعداد تلاش را بر اساس level تنظیم می‌کنیم
     * - game_state را به 1 (Playing) تغییر می‌دهیم
     */
    if (strcmp(mode, "start") == 0) {
        // تولید عدد تصادفی بین 1 تا 100
        secret = get_random_int(1, 100);

        // تنظیم بازه اولیه
        min_range = 1;
        max_range = 100;

        // تنظیم تعداد تلاش بر اساس سطح دشواری
        if (level == LEVEL_EASY) attempts = 10;       // آسان: 10 تلاش
        else if (level == LEVEL_MEDIUM) attempts = 7; // متوسط: 7 تلاش
        else if (level == LEVEL_HARD) attempts = 5;   // سخت: 5 تلاش

        // تغییر وضعیت به "در حال بازی"
        game_state = 1;
    }
    /*
     * حالت play: کاربر یک حدس زده و ما باید آن را بررسی کنیم
     *
     * در این حالت:
     * - حدس را با secret مقایسه می‌کنیم
     * - اگر درست بود → game_state = 2 (Win)
     * - اگر اشتباه بود:
     *   - attempts را کم می‌کنیم
     *   - اگر attempts = 0 شد → game_state = 3 (Lose)
     *   - در حالت آسان، بازه را تنگ می‌کنیم
     */
    else if (strcmp(mode, "play") == 0) {
        // فرض بر این است که هنوز در حال بازی هستیم
        game_state = 1;

        // بررسی اعتبار حدس
        if (guess == -1) {
            // کاربر عدد معتبر وارد نکرده (نباید اتفاق بیفتد اما safe programming)
            printf("<p style='color:red;'>⚠️ لطفاً یک عدد معتبر وارد کنید!</p>");
        } else {
            // بررسی حدس
            if (guess == secret) {
                // ✅ حدس درست بود!
                game_state = 2; // برد
            } else {
                // ❌ حدس اشتباه بود

                // کاهش تعداد تلاش‌های باقی‌مانده
                attempts--;

                if (attempts <= 0) {
                    // تلاش‌ها تمام شد → باخت
                    game_state = 3;
                } else {
                    // هنوز تلاش باقی مانده

                    /*
                     * ویژگی خاص حالت آسان: تنگ کردن بازه
                     *
                     * در حالت آسان، بعد از هر حدس اشتباه، بازه را
                     * براساس حدس تنگ‌تر می‌کنیم تا کاربر راهنمایی بیشتری داشته باشد.
                     *
                     * مثال:
                     * - secret = 75، min=1، max=100
                     * - guess = 50 → min=51 (چون 50 < 75)
                     * - guess = 90 → max=89 (چون 90 > 75)
                     */
                    if (level == LEVEL_EASY) {
                        // اگر حدس کمتر از secret بود، min را بالا ببر
                        if (guess < secret && guess >= min_range) {
                            min_range = guess + 1;
                        }
                        // اگر حدس بیشتر از secret بود، max را پایین بیاور
                        if (guess > secret && guess <= max_range) {
                            max_range = guess - 1;
                        }
                    }
                }
            }
        }
    }

    // ───────────────────────────────────────────────────────────────────────
    // بخش ۵: رندر UI (User Interface)
    // ───────────────────────────────────────────────────────────────────────

    /*
     * بر اساس game_state، صفحه مناسب را render می‌کنیم.
     *
     * game_state ها:
     * - 0: منوی انتخاب سطح دشواری
     * - 1: صفحه بازی (در حال حدس زدن)
     * - 2: صفحه برد
     * - 3: صفحه باخت
     */

    if (game_state == 0) {
        // ═══════════════════════════════════════════════════════════════════
        // منوی اصلی - انتخاب سطح دشواری
        // ═══════════════════════════════════════════════════════════════════

        /*
         * این صفحه اولین چیزی است که کاربر می‌بیند.
         *
         * سه دکمه برای سه سطح دشواری:
         * - سبز: آسان (10 تلاش + راهنمایی کامل)
         * - زرد: متوسط (7 تلاش + راهنمایی استاندارد)
         * - قرمز: سخت (5 تلاش + راهنمایی محدود)
         *
         * هر دکمه یک form است که به guess_number.cgi می‌رود
         * با parameters: mode=start و level=1/2/3
         */

        printf("<h2>🎮 انتخاب سطح دشواری</h2>");
        printf("<p>برای شروع، مهارت خود را محک بزنید:</p>");

        printf("<form action='guess_number.cgi' method='GET'>");
        printf("<input type='hidden' name='mode' value='start'>");

        printf("<button type='submit' name='level' value='1' style='border-color:#2ecc71; color:#2ecc71;'>🟢 آسان (۱۰ تلاش + راهنمایی کامل)</button><br><br>");
        printf("<button type='submit' name='level' value='2' style='border-color:#f1c40f; color:#f1c40f;'>🟡 متوسط (۷ تلاش + راهنمایی استاندارد)</button><br><br>");
        printf("<button type='submit' name='level' value='3' style='border-color:#e74c3c; color:#e74c3c;'>🔴 سخت (۵ تلاش + راهنمایی مبهم)</button>");
        printf("</form>");
    }
    else if (game_state == 1) {
        // ═══════════════════════════════════════════════════════════════════
        // صفحه بازی - در حال حدس زدن
        // ═══════════════════════════════════════════════════════════════════

        /*
         * این صفحه اصلی‌ترین بخش بازی است.
         *
         * نمایش می‌دهد:
         * - بازه فعلی (min تا max)
         * - تعداد تلاش‌های باقی‌مانده (با قلب ❤️)
         * - فیدبک آخرین حدس (گرم/سرد)
         * - فرم برای حدس بعدی
         */

        printf("<h2>🤔 عدد را حدس بزنید</h2>");

        // نمایش بازه فعلی
        printf("<div style='font-size: 1.5rem; margin: 20px;'>بازه فعلی: <span style='color:#fff;'>[%d تا %d]</span></div>", min_range, max_range);

        // نمایش تلاش‌های باقی‌مانده با ایموجی قلب
        printf("<div style='margin-bottom: 20px;'>تلاش‌های باقی‌مانده: ");
        for(int i=0; i<attempts; i++) printf("❤️");
        printf("</div>");

        /*
         * فیدبک حدس قبلی (اگر وجود داشته باشد)
         *
         * این بخش فقط اگر:
         * - guess != -1 باشد (یعنی کاربر حدسی زده)
         * - guess != secret باشد (یعنی اشتباه بوده)
         *
         * نمایش می‌دهد:
         * - جهت (بالا/پایین) - فقط در غیر سخت
         * - حرارت (داغ/سرد) بر اساس فاصله
         * - نکته زوج/فرد - فقط در آسان و هر 2 نوبت یکبار
         */
        if (guess != -1 && guess != secret) {
            // محاسبه فاصله مطلق (برای سیستم گرم/سرد)
            int diff = abs(secret - guess);

            printf("<div style='background:#333; padding:10px; border-radius:5px; margin-bottom:15px;'>");

            /*
             * راهنمایی جهت (فقط در حالت‌های آسان و متوسط)
             *
             * در حالت سخت این را نمایش نمی‌دهیم تا سخت‌تر باشد.
             */
            if (level != LEVEL_HARD) {
                if (guess < secret)
                    printf("⬆️ عدد من <b>بزرگتر</b> است.<br>");
                else
                    printf("⬇️ عدد من <b>کوچکتر</b> است.<br>");
            }

            /*
             * سیستم راهنمایی حرارتی (Hot/Cold)
             *
             * بر اساس فاصله مطلق:
             * - 0-5: 🔥 خیلی داغ (بسیار نزدیک)
             * - 6-15: ♨️ گرم (نسبتاً نزدیک)
             * - 16-30: ❄️ سرد (دور)
             * - 31+: 🧊 یخبندان (خیلی دور)
             *
             * این سیستم در تمام سطوح فعال است.
             */
            if (diff <= 5)
                printf("🔥 <b>خیلی داغ!</b> (بسیار نزدیک)");
            else if (diff <= 15)
                printf("♨️ <b>گرم</b> (نسبتاً نزدیک)");
            else if (diff <= 30)
                printf("❄️ <b>سرد</b> (دور)");
            else
                printf("🧊 <b>یخبندان</b> (خیلی دور!)");

            /*
             * نکته اضافی در حالت آسان: زوج/فرد بودن
             *
             * هر دو نوبت یکبار (attempts زوج باشد)، این نکته را نمایش می‌دهیم:
             * - "عدد مخفی زوج است"
             * - "عدد مخفی فرد است"
             *
             * این فقط برای سطح آسان است تا بازیکن بیشتر راهنمایی شود.
             */
            if (level == LEVEL_EASY && attempts % 2 == 0) {
                printf("<br>💡 نکته: عدد مخفی %s است.",
                       (secret % 2 == 0) ? "زوج" : "فرد");
            }

            printf("</div>");
        }

        /*
         * فرم ورودی حدس بعدی
         *
         * این فرم:
         * - تمام state را در hidden fields نگه می‌دارد
         * - یک input number برای حدس جدید دارد
         * - با submit، به guess_number.cgi با mode=play می‌رود
         *
         * Hidden fields:
         * - mode: play
         * - level: سطح دشواری
         * - secret: عدد مخفی (مهم!)
         * - attempts: تلاش‌های باقی‌مانده
         * - min, max: بازه فعلی
         *
         * Input:
         * - type=number: فقط عدد قبول می‌کند
         * - min/max: محدود به بازه فعلی
         * - autofocus: خودکار focus می‌شود
         * - required: باید پر شود
         */
        printf("<form action='guess_number.cgi' method='GET'>");
        printf("<input type='hidden' name='mode' value='play'>");
        printf("<input type='hidden' name='level' value='%d'>", level);
        printf("<input type='hidden' name='secret' value='%d'>", secret);
        printf("<input type='hidden' name='attempts' value='%d'>", attempts);
        printf("<input type='hidden' name='min' value='%d'>", min_range);
        printf("<input type='hidden' name='max' value='%d'>", max_range);

        printf("<input type='number' name='guess' placeholder='عدد اینجا...' autofocus required min='%d' max='%d'>", min_range, max_range);
        printf("<br><button type='submit'>بررسی حدس 🚀</button>");
        printf("</form>");
    }
    else if (game_state == 2) {
        // ═══════════════════════════════════════════════════════════════════
        // صفحه برد - تبریک!
        // ═══════════════════════════════════════════════════════════════════

        /*
         * این صفحه زمانی نمایش داده می‌شود که کاربر عدد را پیدا کرد.
         *
         * نمایش می‌دهد:
         * - پیام تبریک با انیمیشن چشمک‌زن
         * - عدد مخفی
         * - سطح دشواری انتخاب شده
         * - دکمه بازی مجدد
         * - لینک بازگشت به منوی اصلی
         */

        printf("<h1 style='color:#2ecc71; animation: blink 1s infinite;'>🎉 تبریک! 🎉</h1>");
        printf("<h3>شما عدد <b style='color:#fff; font-size:2rem;'>%d</b> را پیدا کردید!</h3>", secret);
        printf("<p>سطح دشواری: %s</p>",
               (level==1)?"آسان":(level==2)?"متوسط":"سخت");
        printf("<br><a href='guess_number.cgi'><button>🔄 بازی مجدد</button></a>");
        printf("<br><br><a href='../index.html' target='_top' style='color:#aaa; text-decoration:none;'>🏠 بازگشت به منوی اصلی</a>");
    }
    else if (game_state == 3) {
        // ═══════════════════════════════════════════════════════════════════
        // صفحه باخت - Game Over
        // ═══════════════════════════════════════════════════════════════════

        /*
         * این صفحه زمانی نمایش داده می‌شود که تلاش‌ها تمام شد.
         *
         * نمایش می‌دهد:
         * - پیام Game Over
         * - عدد مخفی (تا کاربر بداند چه بود)
         * - دکمه تلاش دوباره
         *
         * چرا عدد مخفی را نشان می‌دهیم:
         * - کاربر نباید با حس ابهام باقی بماند
         * - می‌خواهد بداند چقدر نزدیک بود
         * - شفافیت UX را بهتر می‌کند
         */

        printf("<h1 style='color:#e74c3c;'>💀 Game Over 💀</h1>");
        printf("<p>تلاش‌های شما تمام شد.</p>");
        printf("<h3>عدد مخفی <b style='color:#fff;'>%d</b> بود.</h3>", secret);
        printf("<br><a href='guess_number.cgi'><button>🔄 تلاش دوباره</button></a>");
    }

    // ───────────────────────────────────────────────────────────────────────
    // بخش ۶: پایان
    // ───────────────────────────────────────────────────────────────────────

    /*
     * print_footer از c_utils.h می‌آید و:
     * - تگ‌های HTML باز را می‌بندد
     * - footer مشترک را چاپ می‌کند
     * - </body> و </html> را اضافه می‌کند
     */
    print_footer();

    /*
     * return 0 یعنی برنامه موفق بود.
     *
     * در CGI این مهم است چون:
     * - exit code 0 = موفقیت
     * - exit code != 0 = خطا (سرور 500 برمی‌گرداند)
     */
    return 0;
}
