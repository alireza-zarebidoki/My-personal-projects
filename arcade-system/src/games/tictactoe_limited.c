/*
 * main(): نقطه ورود برنامه CGI
 *
 * جریان کار:
 * ──────────
 *
 * 1. چاپ header HTML
 * 2. خواندن state فعلی از URL
 * 3. اعمال حرکت جدید (اگر وجود دارد)
 * 4. چک کردن برد
 * 5. رندر UI (صفحه بازی)
 * 6. چاپ footer HTML
 *
 * CGI Workflow:
 * ─────────────
 *
 * Request → Parse URL → Update State → Check Win → Render UI → Response
 */
int main() {
    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۱: Initialization
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * print_header() از c_utils.h می‌آید.
     *
     * کارش:
     * - چاپ "Content-Type: text/html; charset=UTF-8"
     * - چاپ تگ‌های ابتدایی HTML
     * - ساخت container با استایل مشترک
     *
     * عنوان: "دوز محدود (Limited)"
     */
    print_header("دوز محدود (Limited)");

    /*
     * CSS inline برای کاهش فاصله بالا
     *
     * چرا؟
     * - قاب iframe محدود است
     * - با padding زیاد، بازی از قاب بیرون می‌زند
     * - این override می‌کند تا داخل قاب جا شود
     *
     * !important: اولویت بالا برای override
     */
    printf("<style>.game-container{padding-top:4px!important;}</style>");

    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۲: State Variables
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * آرایه‌های مهره‌ها
     *
     * p1_cells: مهره‌های بازیکن اول (X) - حداکثر 3 تا
     * p2_cells: مهره‌های بازیکن دوم (O) - حداکثر 3 تا
     *
     * هر عنصر یک شماره خانه است (0-8):
     * مثلاً [0, 1, 4] یعنی مهره‌ها در خانه‌های 0، 1، 4
     */
    int p1_cells[MAX_PIECES], p2_cells[MAX_PIECES];

    /*
     * شمارنده تعداد مهره‌ها
     *
     * p1_count: تعداد مهره‌های بازیکن اول (0 تا 3)
     * p2_count: تعداد مهره‌های بازیکن دوم (0 تا 3)
     *
     * با -1 init نمی‌کنم چون 0 حالت معتبر است (هیچ مهره‌ای نداشتن).
     */
    int p1_count = 0, p2_count = 0;

    /*
     * turn: نوبت کیست؟
     *
     * - 1: نوبت بازیکن اول (X)
     * - 2: نوبت بازیکن دوم (O)
     *
     * مقدار پیش‌فرض: 1 (بازی با X شروع می‌شود)
     */
    int turn = 1;

    /*
     * game_over: آیا بازی تمام شده؟
     *
     * - 0: بازی ادامه دارد
     * - 1: بازی تمام شده (کسی برنده شده)
     *
     * وقتی game_over = 1 باشد:
     * - خانه‌ها دیگر کلیک‌پذیر نیستند
     * - پیام برنده نمایش داده می‌شود
     */
    int game_over = 0;

    /*
     * buffer: بافر موقت برای خواندن پارامترها
     *
     * از MAX_BUFFER (تعریف شده در c_utils.h) استفاده می‌کنم.
     */
    char buffer[MAX_BUFFER];

    /*
     * msg: پیام نمایشی برای کاربر
     *
     * نشان می‌دهد:
     * - نوبت کیست؟ ("نوبت بازیکن اول (X)")
     * - کی برنده شد؟ ("بازیکن X برنده شد! 🎉")
     *
     * مقدار پیش‌فرض: نوبت بازیکن اول
     */
    char msg[MAX_BUFFER] = "نوبت بازیکن اول (X)";

    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۳: Reading State from URL
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * خواندن مهره‌های بازیکن اول (p1)
     *
     * URL: ?p1=0,1,4,...
     *
     * جریان:
     * 1. get_param() رشته "0,1,4," را برمی‌گرداند
     * 2. deserialize_cells() آن را به آرایه [0, 1, 4] تبدیل می‌کند
     * 3. p1_count تعداد عناصر را نگه می‌دارد
     */
    get_param("p1", buffer);
    p1_count = deserialize_cells(buffer, p1_cells);

    /*
     * خواندن مهره‌های بازیکن دوم (p2)
     *
     * مشابه p1، فقط برای بازیکن دوم.
     */
    get_param("p2", buffer);
    p2_count = deserialize_cells(buffer, p2_cells);

    /*
     * خواندن نوبت فعلی (turn)
     *
     * URL: ?turn=1 یا ?turn=2
     *
     * buffer[0] چک می‌کنم تا ببینم آیا پارامتر وجود دارد.
     * - اگر buffer خالی باشد: مقدار پیش‌فرض (1) باقی می‌ماند
     * - اگر پر باشد: با atoi() به عدد تبدیل می‌کنم
     */
    get_param("turn", buffer);
    if (buffer[0]) turn = atoi(buffer);

    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۴: Processing Move
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * خواندن حرکت جدید (move)
     *
     * URL: ?move=4 (یعنی کاربر خانه 4 را کلیک کرد)
     *
     * این بخش فقط اگر:
     * - پارامتر move وجود داشته باشد (buffer[0] != 0)
     * - بازی تمام نشده باشد (!game_over)
     *
     * اعمال می‌شود.
     */
    get_param("move", buffer);
    if (buffer[0] && !game_over) {
        /*
         * تبدیل رشته به عدد
         *
         * مثلاً "4" → 4
         */
        int move = atoi(buffer);

        /*
         * ─────────────────────────────────────────────────────────────────
         * پردازش حرکت برای بازیکن اول (X)
         * ─────────────────────────────────────────────────────────────────
         */
        if (turn == 1) {
            /*
             * چک کردن محدودیت 3 مهره (FIFO Logic)
             *
             * اگر قبلاً 3 مهره داشت:
             * - اولین مهره (oldest) را حذف کن
             * - مهره‌های بعدی را یک جا جلو بیاور
             * - count را یکی کم کن
             *
             * مثال:
             * قبل: cells = [0, 1, 4], count = 3
             * بعد: cells = [1, 4, ?], count = 2
             *
             * این همان قانون FIFO است:
             * First In, First Out (اول رسید، اول رفت)
             */
            if (p1_count == MAX_PIECES) {
                // شیفت دادن عناصر به چپ
                for(int i=0; i<MAX_PIECES-1; i++)
                    p1_cells[i] = p1_cells[i+1];

                p1_count--; // حالا یکی کمتر داریم
            }

            /*
             * افزودن مهره جدید
             *
             * مهره جدید را به انتهای آرایه اضافه می‌کنم.
             * count را افزایش می‌دهم.
             */
            p1_cells[p1_count++] = move;

            /*
             * چک کردن برد
             *
             * اگر این حرکت باعث برد شد:
             * - پیام تبریک با رنگ سبز (#2ecc71)
             * - game_over = 1 تا بازی قفل شود
             *
             * اگر برنده نشد:
             * - نوبت را عوض کن (turn = 2)
             * - پیام را به نوبت بازیکن دوم تغییر بده
             */
            if (check_win(p1_cells, p1_count)) {
                sprintf(msg, "<span style='color:#2ecc71'>بازیکن X برنده شد! 🎉</span>");
                game_over = 1;
            } else {
                turn = 2;
                sprintf(msg, "نوبت بازیکن دوم (O)");
            }
        }
        /*
         * ─────────────────────────────────────────────────────────────────
         * پردازش حرکت برای بازیکن دوم (O)
         * ─────────────────────────────────────────────────────────────────
         *
         * دقیقاً مشابه بالا، فقط برای بازیکن دوم:
         * - رنگ پیام آبی (#3498db)
         * - بعد از حرکت، نوبت را به 1 برمی‌گردانم
         */
        else {
            /*
             * FIFO برای بازیکن دوم
             */
            if (p2_count == MAX_PIECES) {
                for(int i=0; i<MAX_PIECES-1; i++)
                    p2_cells[i] = p2_cells[i+1];
                p2_count--;
            }

            /*
             * افزودن مهره جدید
             */
            p2_cells[p2_count++] = move;

            /*
             * چک برد و تغییر نوبت
             */
            if (check_win(p2_cells, p2_count)) {
                sprintf(msg, "<span style='color:#3498db'>بازیکن O برنده شد! 🎉</span>");
                game_over = 1;
            } else {
                turn = 1;
                sprintf(msg, "نوبت بازیکن اول (X)");
            }
        }
    }


    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۵: Rendering UI
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * قبل از رندر، باید state فعلی را دوباره serialize کنم
     * تا در لینک‌های خانه‌ها قرار بدهم.
     *
     * چرا؟
     * - هر خانه یک لینک به خودش دارد + حرکت جدید
     * - مثلاً: ?p1=0,1,&p2=3,&turn=1&move=4
     * - state فعلی باید حفظ شود
     */
    char p1_str[50], p2_str[50];
    serialize_cells(p1_cells, p1_count, p1_str);
    serialize_cells(p2_cells, p2_count, p2_str);

    /*
     * عنوان بازی با ایموجی
     *
     * ❌ برای X
     * ⭕ برای O
     */
    printf("<h2>❌ Tic Tac Toe Limited ⭕</h2>");

    /*
     * نمایش پیام وضعیت
     *
     * دو حالت:
     * ─────────
     *
     * 1. اگر بازی تمام شده (game_over):
     *    - قاب با border سبز
     *    - پس‌زمینه با opacity کم
     *    - فونت بزرگتر و bold
     *    - پیام برنده نمایش داده می‌شود
     *
     * 2. اگر بازی ادامه دارد:
     *    - استایل ساده
     *    - فقط نوبت فعلی را نشان بده
     */
    if (game_over) {
        /*
         * استایل برنده:
         * - border: 2px solid #10b981 (سبز neon)
         * - background: rgba(16, 185, 129, 0.2) (سبز شفاف)
         * - font-size: 1.8rem (بزرگ)
         * - font-weight: bold
         *
         * این باعث می‌شود پیام برنده خیلی بارز باشد.
         */
        printf("<div style='margin: 15px; font-size: 1.8rem; font-weight: bold; border: 2px solid #10b981; padding: 10px; background: rgba(16, 185, 129, 0.2);'>%s</div>", msg);
    } else {
        /*
         * استایل عادی برای نوبت جاری
         */
        printf("<div style='margin: 10px; font-size: 1.2rem;'>%s</div>", msg);
    }

    /*
     * ─────────────────────────────────────────────────────────────────────
     * صفحه بازی (3x3 Grid)
     * ─────────────────────────────────────────────────────────────────────
     *
     * از CSS Grid استفاده می‌کنم:
     * - grid-template-columns: repeat(3, 80px) → 3 ستون، هر کدام 80px
     * - gap: 10px → فاصله بین خانه‌ها
     * - justify-content: center → وسط‌چین
     *
     * هر خانه یک div یا link است.
     */
    printf("<div style='display: grid; grid-template-columns: repeat(3, 80px); gap: 10px; justify-content: center; margin: 20px auto;'>");

    /*
     * حلقه برای تمام 9 خانه
     *
     * خانه‌ها از 0 تا 8 شماره‌گذاری شده‌اند:
     *
     *     0 | 1 | 2
     *    ---+---+---
     *     3 | 4 | 5
     *    ---+---+---
     *     6 | 7 | 8
     */
    for (int i = 0; i < 9; i++) {
        /*
         * متغیرهای محلی برای این خانه
         *
         * content:
         * - 0: خالی
         * - 1: متعلق به X
         * - 2: متعلق به O
         *
         * is_oldest:
         * - 0: این مهره جدید است یا میانی
         * - 1: این قدیمی‌ترین مهره است (با حرکت بعدی حذف می‌شود)
         */
        int content = 0;
        int is_oldest = 0;

        /*
         * بررسی مهره‌های بازیکن اول (X)
         *
         * اگر این خانه در آرایه p1_cells باشد:
         * - content = 1 (متعلق به X)
         *
         * اگر این خانه اولین عنصر باشد (k==0) و تعداد مهره‌ها 3 تا باشد:
         * - is_oldest = 1 (با حرکت بعدی حذف می‌شود)
         */
        for(int k=0; k<p1_count; k++) {
            if(p1_cells[k] == i) {
                content = 1;
                if(k==0 && p1_count==3) is_oldest=1;
            }
        }

        /*
         * بررسی مهره‌های بازیکن دوم (O)
         *
         * مشابه بالا، فقط برای p2_cells.
         */
        for(int k=0; k<p2_count; k++) {
            if(p2_cells[k] == i) {
                content = 2;
                if(k==0 && p2_count==3) is_oldest=1;
            }
        }

        /*
         * استایل پایه برای هر خانه
         *
         * - width/height: 80x80px (مربع)
         * - border-radius: 10px (گوشه‌های گرد)
         * - font-size: 2.5rem (برای X و O بزرگ)
         * - display: flex + center (برای وسط‌چین محتوا)
         * - border: 2px solid #333 (حاشیه تیره)
         */
        char style[250] = "width:80px; height:80px; border-radius:10px; font-size:2.5rem; display:flex; align-items:center; justify-content:center; border:2px solid #333;";

        /*
         * ═══════════════════════════════════════════════════════════════════
         * حالت ۱: خانه خالی
         * ═══════════════════════════════════════════════════════════════════
         */
        if (content == 0) {
            /*
             * اگر بازی ادامه دارد:
             * - خانه را به یک لینک تبدیل کن
             * - کلیک → ارسال حرکت جدید
             *
             * اگر بازی تمام شده:
             * - خانه را غیرفعال کن (فقط یک div)
             * - cursor: default (بدون hover effect)
             */
            if (!game_over) {
                /*
                 * ساخت لینک کلیک‌پذیر
                 *
                 * URL:
                 * tictactoe_limited.cgi?p1=...&p2=...&turn=...&move=i
                 *
                 * p1_str و p2_str: state فعلی
                 * turn: نوبت فعلی
                 * move=i: خانه کلیک شده
                 *
                 * استایل:
                 * - background: #1e293b (تیره)
                 * - color: transparent (متن نامرئی)
                 * - text-decoration: none (بدون underline)
                 *
                 * محتوا: "." (یک نقطه نامرئی برای قابلیت کلیک)
                 */
                printf("<a href='tictactoe_limited.cgi?p1=%s&p2=%s&turn=%d&move=%d' style='text-decoration:none;'>", p1_str, p2_str, turn, i);
                printf("<div style='%s background:#1e293b; color:transparent;'>.</div>", style);
                printf("</a>");
            } else {
                /*
                 * خانه غیرفعال (بازی تمام شده)
                 *
                 * - background: #111 (سیاه)
                 * - cursor: default (بدون pointer)
                 */
                printf("<div style='%s background:#111; cursor: default;'></div>", style);
            }
        }
        /*
         * ═══════════════════════════════════════════════════════════════════
         * حالت ۲: خانه پر (X یا O)
         * ═══════════════════════════════════════════════════════════════════
         */
        else {
            /*
             * افکت ویژه برای قدیمی‌ترین مهره
             *
             * اگر:
             * - is_oldest = 1 (اولین مهره در آرایه)
             * - بازی ادامه دارد (!game_over)
             *
             * آنگاه استایل ویژه اعمال می‌شود:
             * - opacity: 0.4 (کمرنگ/شفاف)
             * - border-style: dotted (حاشیه نقطه‌چین)
             * - filter: grayscale(1) (سیاه و سفید)
             *
             * این به بازیکن نشان می‌دهد که این مهره با حرکت بعدی حذف می‌شود!
             *
             * این یک "نمره مازاد" است - یعنی امتیاز خلاقیت اضافه!
             */
            if (is_oldest && !game_over) {
                strcat(style, "opacity: 0.4; border-style: dotted; filter: grayscale(1);");
            }

            /*
             * تعیین رنگ و سمبل
             *
             * بازیکن اول (X):
             * - color: #e74c3c (قرمز)
             * - symbol: "X"
             *
             * بازیکن دوم (O):
             * - color: #3498db (آبی)
             * - symbol: "O"
             */
            char* color = (content == 1) ? "#e74c3c" : "#3498db";
            char* symbol = (content == 1) ? "X" : "O";

            /*
             * رندر کردن مهره
             *
             * - background: #000 (سیاه)
             * - color: رنگ بازیکن
             * - box-shadow: glow effect (درخشش اطراف)
             */
            printf("<div style='%s background:#000; color:%s; box-shadow: 0 0 10px %s;'>%s</div>", style, color, color, symbol);
        }
    }

    /*
     * پایان grid
     */
    printf("</div>");

    /*
     * ─────────────────────────────────────────────────────────────────────
     * دکمه شروع مجدد
     * ─────────────────────────────────────────────────────────────────────
     *
     * لینک به tictactoe_limited.cgi بدون پارامتر
     * → state کاملاً reset می‌شود
     * → بازی از صفر شروع می‌شود
     *
     * استایل:
     * - background: #f1c40f (زرد)
     * - ایموجی: 🔄 (چرخش)
     */
    printf("<br><a href='tictactoe_limited.cgi'><button style='background:#f1c40f;'>🔄 شروع مجدد</button></a>");

    /*
     * ─────────────────────────────────────────────────────────────────────
     * راهنمایی برای کاربران جدید
     * ─────────────────────────────────────────────────────────────────────
     *
     * فقط اگر بازی ادامه دارد (!game_over)، این متن نمایش داده می‌شود:
     *
     * "قانون: با گذاشتن مهره چهارم، مهره اول (کمرنگ) حذف می‌شود."
     *
     * استایل:
     * - font-size: 0.8rem (کوچک)
     * - color: #aaa (خاکستری)
     *
     * این توضیح مهم است تا بازیکن بفهمد چرا برخی مهره‌ها کمرنگ هستند.
     */
    if (!game_over) {
        printf("<br><br><div style='font-size:0.8rem; color:#aaa;'>قانون: با گذاشتن مهره چهارم، مهره اول (کمرنگ) حذف می‌شود.</div>");
    }

    // ═══════════════════════════════════════════════════════════════════════
    // بخش ۶: پایان
    // ═══════════════════════════════════════════════════════════════════════

    /*
     * print_footer() از c_utils.h می‌آید.
     *
     * - تگ‌های HTML را می‌بندد
     * - footer مشترک را چاپ می‌کند
     */
    print_footer();

    /*
     * return 0 → موفقیت
     *
     * این مهم است چون سرور CGI exit code را چک می‌کند.
     */
    return 0;
}

